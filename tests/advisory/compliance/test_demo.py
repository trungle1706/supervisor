"""Demo products: the three demo agents and a corpus repo."""

from __future__ import annotations

import re

import pytest

from supervisor.advisory.compliance.demo import DEMO_AGENTS, corpus_product, demo_product
from supervisor.advisory.compliance.model import ProductProfile

POLICY_PTR = re.compile(r"^policies/baseline\.yaml:\d+$")


@pytest.mark.parametrize("agent", DEMO_AGENTS)
def test_demo_product_builds(agent: str) -> None:
    p = demo_product(agent)
    assert isinstance(p, ProductProfile) and p.product_id == agent and p.source == "onboard"
    assert demo_product(agent) is p  # cached
    c = p.controls
    assert c.known and c.supervised is True and c.basis == "deployed"
    assert c.policy_files == ("policies/baseline.yaml",)
    assert c.rules and all(POLICY_PTR.match(r.pointer.ref) for r in c.rules)
    assert all(r.pointer.kind == "rule" for r in c.rules)


@pytest.mark.parametrize("agent", DEMO_AGENTS)
def test_every_present_control_has_a_pointer(agent: str) -> None:
    c = demo_product(agent).controls
    present = (
        [f"catalogue:{x}" for x in c.catalogue_on]
        + [f"rule:{r.id}" for r in c.rules]
        + [f"monitor:{x}" for x in c.monitors]
        + [f"evidence:{x}" for x in c.evidence]
        + [f"console:{x}" for x in c.console]
    )
    assert present
    missing = [k for k in present if k not in c.pointers]
    assert missing == []
    assert all(c.pointers[k].ref for k in present)
    for k in (f"catalogue:{x}" for x in c.catalogue_on):
        assert c.pointers[k].kind == "plan"


def test_payments_limits() -> None:
    p = demo_product("payments")
    by = {x.id: x for x in p.limits}
    pay02, pay03 = by["PAY-02"], by["PAY-03"]
    assert (pay02.period, pay02.value_vnd) == ("per_transaction", 100_000_000)
    assert (pay03.period, pay03.scope, pay03.value_vnd) == ("daily", "per_customer", 150_000_000)
    assert pay02.pointer and POLICY_PTR.match(pay02.pointer.ref)
    assert pay03.pointer and POLICY_PTR.match(pay03.pointer.ref)
    man = by["daily_transfer_max_minor"]
    assert man.source == "manifest" and man.value_vnd == 300_000_000 and man.scope == "per_customer"
    assert man.pointer and man.pointer.ref.endswith("manifest.yaml:17")
    assert all(x.pointer is not None for x in p.limits)
    assert all(type(x.value_vnd) is int for x in p.limits)


def test_only_payments_has_a_demo_answer() -> None:
    assert demo_product("payments").customer_types == ("individual",)
    assert demo_product("payments").customer_types_complete is True
    p = demo_product("payments").provenance["customer_types"][0]
    assert p.kind == "questionnaire"
    for other in ("credit_prequal", "customer_service"):
        assert demo_product(other).customer_types is None


def test_unknown_names_rejected() -> None:
    with pytest.raises(ValueError):
        demo_product("nope")
    with pytest.raises(ValueError):
        corpus_product("../etc")


def test_corpus_product_builds() -> None:
    p = corpus_product("fastapi_toolserver_remit")
    assert p.source == "onboard" and p.product_id
    assert p.controls.basis == "planned" and p.controls.known
    assert "payment" in (p.agent_classes or ())
    # the policy the Onboarding Agent would propose (render_policy), as in the launch pack
    assert p.controls.rules and all(r.id.startswith("OB-") for r in p.controls.rules)
    assert all("generated by onboarding" in r.pointer.ref for r in p.controls.rules)
    assert all(x.pointer is not None for x in p.limits)
    assert corpus_product("fastapi_toolserver_remit") is p
