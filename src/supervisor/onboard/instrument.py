"""Stage 4 Instrument: policy YAML, tracing/gate hook codemod, dashboard spec, alert routes,
and a branch with one commit in a COPY or clone of the target repository.

* The policy YAML is rendered from the plan and validated with the gateway loader
  (``supervisor.gateway.policy``) before anything is written.
* The codemod is deterministic: ``ast`` locates the agent's builder function (a
  function with a ``gate`` parameter); a text template inserts two lines that default
  the gate hook and the tracer provider to the Supervisor ones. No LLM writes code.
* Git runs only through ``supervisor.sandbox.git`` (allow-listed subcommands: no merge,
  no push). The original repository is never written: the branch lives in a clone (or
  a copy) under the work folder. A human opens and merges the pull request.
"""

from __future__ import annotations

import ast
import json
import os
import re
import shutil
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import yaml

from supervisor import sandbox
from supervisor.core.errors import SandboxError, SupervisorError
from supervisor.gateway.policy import Policy, load_policy_texts
from supervisor.onboard.models import (
    AgentProfile,
    InstrumentResult,
    Inventory,
    MonitoringPlan,
    RemediationPlaybook,
)

ONBOARD_DIR = "supervisor_onboarding"
HOOK_MODULE = "supervisor_onboard"
MARKER = "# supervisor-onboard: hook"
GIT_NAME = "Supervisor Onboarding Agent"
GIT_EMAIL = "onboarding-agent@example.invalid"


class InstrumentError(SupervisorError):
    """Instrument could not prepare the branch."""


def branch_name(agent_id: str) -> str:
    return "supervisor/onboard-" + re.sub(r"[^a-z0-9_-]", "-", agent_id.lower())[:60]


# --------------------------------------------------------------------------- policy


def render_policy(inv: Inventory, profile: AgentProfile, mp: MonitoringPlan) -> str:
    """Policy YAML for this agent (initial_state SHADOW). Validated before return."""
    doc: dict[str, Any] = {
        "policy_version": 1,
        "tools": {t.name: t.risk_class for t in inv.tools},
        "agents": {
            inv.agent_id: {
                "name": inv.name,
                "owner_user": inv.owner_user,
                "owner_team": inv.owner_team,
                "risk_tier": profile.proposed_risk_tier,
                "model_family": inv.model_family,
                "host_type": inv.host_type,
                "plug_point": inv.plug_point,
                "initial_state": "SHADOW",
            }
        },
        "rules": [r.spec for r in mp.rules],
    }
    header = (
        f"# Supervisor policy for agent {inv.agent_id} - generated by the Onboarding Agent.\n"
        "# Review every rule. Replace each FILL-ME-approver with two named approvers before\n"
        "# merge. The agent starts in SHADOW: rules are evaluated and recorded, nothing is\n"
        "# blocked until a rule is switched to enforced mode (see the launch report).\n"
        "# Schema: policies/schema.json (supervisor.gateway.policy).\n"
    )
    text = header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)
    validate_policy(text)
    return text


def validate_policy(text: str, source: str = "generated_policy.yaml") -> Policy:
    """Load with the gateway loader (strict schema + cross checks). Raises PolicyError."""
    return load_policy_texts([(source, text)])


# --------------------------------------------------------------------------- dashboard, routes


def render_dashboard(inv: Inventory, mp: MonitoringPlan) -> dict[str, Any]:
    panels: list[dict[str, Any]] = [
        {
            "id": "gate_decisions",
            "title": "Gate decisions by action",
            "viz": "timeseries",
            "query": {
                "table": "agent_event",
                "filter": {"agent_id": inv.agent_id, "event_type": "gate_decision"},
                "group_by": ["status"],
            },
        },
        {
            "id": "tool_mix",
            "title": "Tool calls by tool (drift vs launch baseline)",
            "viz": "bar",
            "query": {
                "table": "agent_event",
                "filter": {"agent_id": inv.agent_id, "event_type": "tool_call"},
                "group_by": ["tool_name"],
            },
        },
        {
            "id": "rule_matches",
            "title": "Rule matches (shadow and enforced)",
            "viz": "table",
            "query": {"table": "verdict", "filter": {"agent_id": inv.agent_id, "tier": 0}},
        },
        {
            "id": "open_cases",
            "title": "Open cases",
            "viz": "stat",
            "query": {"table": "cases", "filter": {"agent_id": inv.agent_id, "status": "open"}},
        },
    ]
    for c in mp.capabilities:
        if c.status == "on" and c.kind in ("judge", "monitor"):
            panels.append(
                {
                    "id": c.id,
                    "title": c.name,
                    "viz": "timeseries",
                    "query": {
                        "table": "verdict",
                        "filter": {"agent_id": inv.agent_id, "judge": c.id},
                    },
                }
            )
    return {
        "dashboard_version": 1,
        "agent_id": inv.agent_id,
        "title": f"Supervisor - {inv.name}",
        "panels": panels,
        "thresholds": dict(sorted(mp.thresholds.items())),
    }


def render_alert_routes(inv: Inventory, playbook: RemediationPlaybook) -> str:
    routes = []
    for sev, minutes in (("critical", 5), ("high", 30), ("medium", 240), ("low", 1440)):
        triggers = [e.trigger for e in playbook.entries if e.severity == sev]
        if not triggers:
            continue
        routes.append(
            {
                "match": {"agent_id": inv.agent_id, "severity": sev},
                "channel": f"inbox:{inv.owner_team}",
                "notify": [inv.owner_user],
                "escalate_after_minutes": minutes,
                "escalate_to": "FILL-ME-escalation-group",
                "triggers": triggers,
            }
        )
    doc = {"alert_routes_version": 1, "agent_id": inv.agent_id, "routes": routes}
    return "# Alert routes - generated by the Onboarding Agent. Review before merge.\n" + (
        yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)
    )


# --------------------------------------------------------------------------- codemod

HOOK_TEMPLATE = '''"""Supervisor hook for agent {agent_id} - generated by the Onboarding Agent.

Review before merge. ``default_gate()`` returns the Supervisor gate hook when
SUPERVISOR_GATE_URL is set (HTTP gate; read-only tools fail open, every other tool
fails closed when the gateway is unreachable). ``default_tracer_provider()`` returns a
tracer provider that tags spans with the agent id, or None to keep the agent default.
"""

from __future__ import annotations

import os
from typing import Any

AGENT_ID = {agent_id!r}
TOOL_RISK = {tool_risk!r}


def default_gate() -> Any:
    url = os.environ.get("SUPERVISOR_GATE_URL", "")
    if not url:
        return None
    from supervisor.gateway.sdk import HttpGate

    return HttpGate(url, fail_modes=TOOL_RISK)


def default_tracer_provider() -> Any:
    if os.environ.get("SUPERVISOR_TRACING", "") != "1":
        return None
    from opentelemetry.sdk.resources import Resource
    from opentelemetry.sdk.trace import TracerProvider

    return TracerProvider(
        resource=Resource.create({{"service.name": AGENT_ID, "supervisor.agent_id": AGENT_ID}})
    )
'''


def render_hook_module(inv: Inventory) -> str:
    text = HOOK_TEMPLATE.format(
        agent_id=inv.agent_id, tool_risk={t.name: t.risk_class for t in inv.tools}
    )
    ast.parse(text)  # template must stay valid Python
    return text


def apply_codemod(source: str, *, import_line: str) -> tuple[str, bool, str]:
    """Insert the gate/tracer defaults at the top of the builder function.

    Returns (new_source, applied, note). Idempotent (marker comment). The builder is the
    first top-level function with a ``gate`` parameter (``build_agent`` preferred)."""
    if MARKER in source:
        return source, False, "hook already present"
    tree = ast.parse(source)
    fns = [
        n
        for n in tree.body
        if isinstance(n, ast.FunctionDef)
        and any(a.arg == "gate" for a in [*n.args.args, *n.args.kwonlyargs])
    ]
    fns.sort(key=lambda n: (n.name != "build_agent", n.lineno))
    if not fns:
        return source, False, "no builder function with a gate parameter: wire the hook by hand"
    fn = fns[0]
    params = {a.arg for a in [*fn.args.args, *fn.args.kwonlyargs]}
    body = fn.body
    first = body[0]
    if (
        isinstance(first, ast.Expr)
        and isinstance(first.value, ast.Constant)
        and isinstance(first.value.value, str)
        and len(body) > 1
    ):
        first = body[1]
    lines = source.splitlines(keepends=True)
    indent = " " * first.col_offset
    insert = [f"{indent}{MARKER} (generated, review before merge)\n"]
    insert.append(f"{indent}gate = gate if gate is not None else {HOOK_MODULE}.default_gate()\n")
    if "tracer_provider" in params:
        insert.append(
            f"{indent}tracer_provider = (\n"
            f"{indent}    tracer_provider\n"
            f"{indent}    if tracer_provider is not None\n"
            f"{indent}    else {HOOK_MODULE}.default_tracer_provider()\n"
            f"{indent})\n"
        )
    at = first.lineno - 1
    lines[at:at] = insert
    # import after the last top-level import
    imports = [n for n in tree.body if isinstance(n, ast.Import | ast.ImportFrom)]
    imp_at = (imports[-1].end_lineno or imports[-1].lineno) if imports else 0
    shift = len(insert) if imp_at > at else 0
    lines[imp_at + shift : imp_at + shift] = [import_line + "  " + MARKER + "\n"]
    new = "".join(lines)
    ast.parse(new)
    return new, True, f"gate and tracer defaults inserted in {fn.name}()"


# --------------------------------------------------------------------------- git


def _git(args: list[str], cwd: Path, timeout_s: float = 120.0) -> str:
    res = sandbox.git(args, cwd=cwd, timeout_s=timeout_s)
    if not res.ok:
        raise InstrumentError(f"git {args[0]} failed: {res.stderr.strip()[:300]}")
    return res.stdout.strip()


def prepare_work_repo(target: Path, work_dir: Path) -> tuple[str, Path, Path, str]:
    """Clone the target's repository (or copy the target into a new repo).

    Returns (mode, repo_dir, target_in_repo, base_ref)."""
    work_dir.mkdir(parents=True, exist_ok=True)
    dest = work_dir / "repo"
    if dest.exists():
        shutil.rmtree(dest)
    try:
        top = Path(_git(["rev-parse", "--show-toplevel"], target))
        prefix = _git(["rev-parse", "--show-prefix"], target)
    except (InstrumentError, SandboxError):
        top = None
        prefix = ""
    if top is not None:
        _git(["clone", "--quiet", "--no-hardlinks", str(top), str(dest)], work_dir, 300.0)
        base = _git(["rev-parse", "--abbrev-ref", "HEAD"], dest)
        return "clone", dest, dest / prefix if prefix else dest, base
    shutil.copytree(
        target,
        dest,
        ignore=shutil.ignore_patterns(".git", "__pycache__", ".venv", "*.pyc"),
    )
    _git(["init", "--quiet", "-b", "main"], dest)
    _git(["add", "--all"], dest)
    _commit(dest, "baseline copy for onboarding")
    return "copy", dest, dest, "main"


def _commit(repo: Path, message: str) -> str:
    res = sandbox.git(
        ["commit", "--quiet", "--no-verify", "-m", message],
        cwd=repo,
        timeout_s=120.0,
        identity=(GIT_NAME, GIT_EMAIL),
    )
    if not res.ok:
        raise InstrumentError(f"git commit failed: {res.stderr.strip()[:300]}")
    return _git(["rev-parse", "HEAD"], repo)


def instrument(
    target: str | Path,
    work_dir: str | Path,
    inv: Inventory,
    profile: AgentProfile,
    mp: MonitoringPlan,
    playbook: RemediationPlaybook,
    *,
    entry_file: str | None = None,
) -> tuple[InstrumentResult, dict[str, str]]:
    """Create branch ``supervisor/onboard-<agent>`` with one commit. Never merges.

    Returns the result and the generated texts (``policy.yaml``, ``dashboard.json``,
    ``alert_routes.yaml``, ``supervisor_onboard.py``)."""
    target = Path(os.path.abspath(target))
    work = Path(os.path.abspath(work_dir))
    policy_text = render_policy(inv, profile, mp)
    policy_hash = validate_policy(policy_text).policy_hash
    texts = {
        "policy.yaml": policy_text,
        "dashboard.json": json.dumps(render_dashboard(inv, mp), indent=2, sort_keys=True) + "\n",
        "alert_routes.yaml": render_alert_routes(inv, playbook),
        f"{HOOK_MODULE}.py": render_hook_module(inv),
    }
    mode, repo, tdir, base_ref = prepare_work_repo(target, work)
    base_sha = _git(["rev-parse", "HEAD"], repo)
    branch = branch_name(inv.agent_id)
    _git(["checkout", "--quiet", "-b", branch], repo)
    out_dir = tdir / ONBOARD_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    changed: list[Path] = []
    for name in ("policy.yaml", "dashboard.json", "alert_routes.yaml"):
        (out_dir / name).write_text(texts[name], encoding="utf-8", newline="\n")
        changed.append(out_dir / name)
    (tdir / f"{HOOK_MODULE}.py").write_text(
        texts[f"{HOOK_MODULE}.py"], encoding="utf-8", newline="\n"
    )
    changed.append(tdir / f"{HOOK_MODULE}.py")
    applied, note = False, "no entrypoint found: wire the hook by hand"
    entry = entry_file or next(
        (e.evidence.file for e in inv.entrypoints if e.name == "build_agent" and e.evidence),
        None,
    )
    if entry:
        path = tdir / entry
        rel_pkg = (tdir / "__init__.py").exists()
        import_line = f"from . import {HOOK_MODULE}" if rel_pkg else f"import {HOOK_MODULE}"
        new, applied, note = apply_codemod(
            path.read_text(encoding="utf-8"), import_line=import_line
        )
        if applied:
            path.write_text(new, encoding="utf-8", newline="\n")
            changed.append(path)
    rels = [p.relative_to(repo).as_posix() for p in changed]
    _git(["add", "--", *rels], repo)
    message = (
        f"Supervisor onboarding for {inv.agent_id}: policy (shadow), hooks, dashboard, alerts\n\n"
        "Generated by the Supervisor Onboarding Agent. Do not merge without review by the\n"
        "agent owner and a second approver. Replace every FILL-ME value first.\n"
    )
    commit = _commit(repo, message)
    head_branch = _git(["rev-parse", "--abbrev-ref", "HEAD"], repo)
    if head_branch != branch:
        raise InstrumentError(f"expected to be on {branch}, found {head_branch}")
    return (
        InstrumentResult(
            mode=mode,  # type: ignore[arg-type]
            work_repo=str(repo),
            branch=branch,
            base_ref=base_ref,
            base_sha=base_sha,
            commit_sha=commit,
            files_changed=sorted(rels),
            codemod_applied=applied,
            codemod_note=note,
            policy_hash=policy_hash,
        ),
        texts,
    )


# --------------------------------------------------------------------------- PR description


def render_pr_description(
    inv: Inventory,
    profile: AgentProfile,
    mp: MonitoringPlan,
    result: InstrumentResult,
    launch_summary: Mapping[str, Any] | None = None,
) -> str:
    d33 = profile.decision33
    lines = [
        f"# Supervisor onboarding: {inv.name} (`{inv.agent_id}` {inv.version})",
        "",
        "Generated by the Supervisor Onboarding Agent. **Never auto-merged.** The agent "
        "owner and a second approver review and merge.",
        "",
        f"- Branch: `{result.branch}` (base `{result.base_ref}` at `{result.base_sha[:12]}`)",
        f"- Commit: `{result.commit_sha[:12]}`",
        f"- Policy hash: `{result.policy_hash[:16]}`; agent starts in **SHADOW**",
        f"- Codemod: {result.codemod_note}",
        "",
        "## Profile",
        "",
        f"- Purpose: {profile.purpose.claim}",
        f"- Proposed risk tier: **{profile.proposed_risk_tier}** "
        f"(declared: {profile.declared_risk_tier or 'none'}); a human confirms",
        f"- Decision 33 (proposal, by default): **{d33.classification}**",
    ]
    for e in d33.entries:
        refs = ", ".join(ev.ref() for ev in e.evidence[:3])
        lines.append(f"  - {e.entry}: triggered={e.triggered}; {e.reason} ({refs})")
    lines += ["", f"> {d33.wording_caveat}", "", "## Weak spots", ""]
    for w in profile.weak_spots:
        lines.append(f"- {w.claim} ({', '.join(ev.ref() for ev in w.evidence[:2])})")
    if not profile.weak_spots:
        lines.append("- none found by the deterministic checks")
    lines += [
        "",
        "## Rules (gateway policy, shadow first)",
        "",
        "| Rule | Capability | Action | Severity | Description |",
        "|---|---|---|---|---|",
    ]
    for r in mp.rules:
        s = r.spec
        lines.append(
            f"| {r.rule_id} | {r.capability_id} | {s['action']} | {s['severity']} | "
            f"{s['description'].replace('|', '/')} |"
        )
    lines += ["", "## Files", ""] + [f"- `{f}`" for f in result.files_changed]
    if launch_summary:
        lines += ["", "## Launch (shadow, sandbox)", ""]
        for k, v in launch_summary.items():
            lines.append(f"- {k}: {v}")
    lines += [
        "",
        "## Reviewer checklist",
        "",
        "- [ ] Replace both `FILL-ME-approver-*` values on every block/pause rule with named "
        "approvers (two different people).",
        "- [ ] Check each rule's evidence (file:line in `profile.md`).",
        "- [ ] Confirm the risk tier and the Decision 33 classification with risk and legal.",
        "- [ ] Merge into the policy repo; keep the agent in SHADOW; switch rules to "
        "enforced one by one as the launch report recommends.",
        "- [ ] The agent's own test suite passes with the hook module.",
        "",
    ]
    return "\n".join(lines)
