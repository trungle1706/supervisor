RISK_CLASSES = ("read_only", "money", "credit", "pii_export")
GATE_PATH = "/v1/gate/check"
LEGACY_GATE_PATH = "/gate/check"  # used when the address already ends in /v1
MIN_SECRET_CHARS = 32
H_AGENT = "X-Supervisor-Agent"
H_SIGNATURE = "X-Supervisor-Signature"
H_TIMESTAMP = "X-Supervisor-Timestamp"
H_NONCE = "X-Supervisor-Nonce"


class SupervisorBlocked(Exception):
    """Guardian refused the call. ``decision`` holds the answer of Guardian."""

    def __init__(self, decision: Mapping[str, Any]) -> None:
        self.decision = dict(decision)
        rule = self.decision.get("rule_id")
        reason = self.decision.get("reason", "blocked")
        super().__init__(f"blocked by guardian ({rule}): {reason}")


class SupervisorPaused(SupervisorBlocked):
    """Guardian paused the agent (or the agent was already paused)."""


class CredentialError(Exception):
    """The credential cannot be loaded (no key, key too short, key file open to others)."""


