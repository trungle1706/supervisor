def string_to_sign(
    agent_id: str, timestamp: str, nonce: str, method: str, path: str, body_hash: str
) -> bytes:
    """The text that is signed. Same text as the Guardian server builds."""
    parts = ("v1", agent_id, timestamp, nonce, method.upper(), path, body_hash)
    return "\n".join(parts).encode("utf-8")


def sign(
    secret: str, agent_id: str, timestamp: str, nonce: str, method: str, path: str, body: bytes
) -> str:
    """``v1=<hex>``: HMAC-SHA256 over the string to sign, with the key as UTF-8 bytes."""
    digest = hashlib.sha256(body).hexdigest()
    text = string_to_sign(agent_id, timestamp, nonce, method, path, digest)
    return "v1=" + hmac.new(secret.encode("utf-8"), text, hashlib.sha256).hexdigest()


class HmacCredential:
    """A key shared with Guardian. Each request gets a fresh time stamp and nonce."""

    def __init__(self, agent_id: str, secret: str, clock: Callable[[], float] = time.time) -> None:
        if len(secret) < MIN_SECRET_CHARS:
            raise CredentialError(f"the key must have at least {MIN_SECRET_CHARS} characters")
        self.agent_id = agent_id
        self._secret = secret
        self._clock = clock

    def __repr__(self) -> str:
        return f"HmacCredential(agent={self.agent_id})"

    def headers_for(self, method: str, path: str, body: bytes) -> dict[str, str]:
        ts = str(int(self._clock()))
        nonce = secrets.token_urlsafe(18)
        signature = sign(self._secret, self.agent_id, ts, nonce, method, path, body)
        return {H_AGENT: self.agent_id, H_TIMESTAMP: ts, H_NONCE: nonce, H_SIGNATURE: signature}


class BrokenCredential:
    """Stands in for a credential that could not be loaded: every call is answered GATE-AUTH."""

    def __init__(self, reason: str) -> None:
        self.reason = reason

    def headers_for(self, method: str, path: str, body: bytes) -> dict[str, str]:
        raise CredentialError(self.reason)


class BearerCredential:
    """A bearer token from ``token_headers()`` (for Databricks: ``Config().authenticate``).
    The token is asked for on every call and is not kept."""

    def __init__(self, agent_id: str, token_headers: Callable[[], Mapping[str, str]]) -> None:
        self.agent_id = agent_id
        self._token_headers = token_headers

    def __repr__(self) -> str:
        return f"BearerCredential(agent={self.agent_id})"

    def headers_for(self, method: str, path: str, body: bytes) -> dict[str, str]:
        try:
            got = dict(self._token_headers())
        except Exception as exc:  # noqa: BLE001 - the text of the error may hold a token
            raise CredentialError(f"no token ({type(exc).__name__})") from None
        if not str(got.get("Authorization", "")).startswith("Bearer "):
            raise CredentialError("the sign-in gave no bearer token")
        return {"Authorization": got["Authorization"], H_AGENT: self.agent_id}


def _env(*names: str) -> str:
    for name in names:
        value = os.environ.get(name, "").strip()
        if value:
            return value
    return ""


def credential_from_env(agent_id: str = AGENT_ID) -> Any:
    """A key (file or text) gives HMAC. Else, on Databricks with databricks-sdk, the service
    principal gives a bearer token. None when there is neither (an unsigned call)."""
    kind = (_env("GUARDIAN_AUTH") or "auto").lower()
    path = _env("GUARDIAN_AGENT_KEY_FILE", "SUPERVISOR_AGENT_KEY_FILE")
    secret = _env("GUARDIAN_AGENT_KEY", "SUPERVISOR_AGENT_KEY")
    if kind in ("auto", "hmac") and (path or secret):
        if path:
            secret = _read_key_file(path)
        return HmacCredential(agent_id, secret)
    if kind == "hmac":
        raise CredentialError("GUARDIAN_AUTH=hmac but no key is set")
    if kind == "databricks" or (kind == "auto" and _env("DATABRICKS_HOST", "DATABRICKS_CLIENT_ID")):
        try:
            from databricks.sdk.core import Config  # type: ignore[import-not-found]
        except ImportError:
            if kind == "databricks":
                raise CredentialError("databricks-sdk is not installed") from None
            return None
        try:
            cfg = Config()
        except Exception as exc:  # noqa: BLE001 - the text of the error may hold a secret
            raise CredentialError(f"databricks sign-in failed ({type(exc).__name__})") from None
        return BearerCredential(agent_id, cfg.authenticate)
    return None


def _read_key_file(path: str) -> str:
    try:
        if os.name == "posix" and stat.S_IMODE(os.stat(path).st_mode) & 0o077:
            raise CredentialError("the key file must not be open to others (chmod 600)")
        with open(path, encoding="utf-8") as fh:
            return fh.readline().strip()
    except OSError as exc:
        raise CredentialError(f"cannot read the key file ({type(exc).__name__})") from None


# ----------------------------------------------------------------------------- the request


def build_request(
    base_url: str,
    agent_id: str,
    agent_version: str,
    tool_name: str,
    args: Mapping[str, Any],
    context: Mapping[str, Any] | None = None,
    credential: Any = None,
) -> tuple[str, bytes, dict[str, str]]:
    """(url, body bytes, headers) of one gate check. The body is JSON, ASCII only, and the
    signature covers these exact bytes."""
    base = base_url.rstrip("/")
    path = LEGACY_GATE_PATH if base.endswith("/v1") else GATE_PATH
    url = base + path
    payload = {
        "agent_id": agent_id,
        "agent_version": agent_version,
        "tool_name": tool_name,
        "args": dict(args),
        "context": dict(context) if context is not None else None,
    }
    body = json.dumps(payload, separators=(",", ":"), ensure_ascii=True).encode("ascii")
    headers = credential.headers_for("POST", urlparse(url).path, body) if credential else {}
    headers["Content-Type"] = "application/json"
    return url, body, headers


Transport = Callable[[str, bytes, Mapping[str, str], float], Mapping[str, Any]]


def _post(url: str, body: bytes, headers: Mapping[str, str], timeout_s: float) -> Mapping[str, Any]:
    if urlparse(url).scheme not in ("http", "https"):
        raise ValueError("the Guardian address must start with http:// or https://")
    request = urllib.request.Request(url, data=body, headers=dict(headers), method="POST")  # noqa: S310
    with urllib.request.urlopen(request, timeout=timeout_s) as resp:  # noqa: S310
        data = json.loads(resp.read(1_000_000).decode("utf-8"))
    if not isinstance(data, dict):
        raise ValueError("the answer of Guardian is not an object")
    return data


def _closed(rule_id: str, reason: str) -> dict[str, Any]:
    return {"allow": False, "action": "block", "rule_id": rule_id, "reason": reason}


class HttpGate:
    """Asks Guardian over HTTP. ``check`` never raises: on any fault it answers a block, except a
    read-only tool when Guardian is unreachable (then it answers allow, with action ``alert``)."""

    def __init__(
        self,
        base_url: str,
        credential: Any = None,
        timeout_s: float = 2.0,
        transport: Transport | None = None,
    ) -> None:
        self.base_url = base_url
        self.credential = credential
        self.timeout_s = timeout_s
        self.transport: Transport = transport or _post

    def check(
        self,
        agent_id: str,
        agent_version: str,
        tool_name: str,
        args: Mapping[str, Any],
        context: Mapping[str, Any] | None = None,
    ) -> Mapping[str, Any]:
        read_only = (context or {}).get("declared_risk_class") == "read_only"
        try:
            url, body, headers = build_request(
                self.base_url, agent_id, agent_version, tool_name, args, context, self.credential
            )
        except CredentialError:
            return _closed("GATE-AUTH", "guardian credential missing: fail closed")
        except (TypeError, ValueError):
            return _closed("GATE-ARGS", "the arguments are not plain JSON: fail closed")
        try:
            result = self._call(url, body, headers)
        except Exception as exc:  # noqa: BLE001 - every fault is an answer, never an exception
            status = getattr(exc, "code", None) or getattr(
                getattr(exc, "response", None), "status_code", None
            )
            if status in (401, 403):
                return _closed("GATE-AUTH", "guardian refused the credential: fail closed")
            if read_only:
                return {
                    "allow": True,
                    "action": "alert",
                    "rule_id": "GATE-UNREACHABLE",
                    "reason": "guardian unreachable: fail open (read only)",
                }
            return _closed("GATE-UNREACHABLE", "guardian unreachable: fail closed")
        if not isinstance(result.get("allow"), bool):
            return _closed("GATE-ERROR", "unreadable answer from guardian: fail closed")
        return dict(result)

    def _call(self, url: str, body: bytes, headers: Mapping[str, str]) -> Mapping[str, Any]:
        """Run the transport with a hard deadline, even if the transport ignores its timeout."""
        box: dict[str, Any] = {}

        def run() -> None:
            try:
                box["value"] = self.transport(url, body, headers, self.timeout_s)
            except BaseException as exc:  # noqa: BLE001
                box["error"] = exc

        worker = threading.Thread(target=run, daemon=True)
        worker.start()
        worker.join(self.timeout_s)
        if worker.is_alive():
            raise TimeoutError("guardian call timed out")
        if "error" in box:
            raise box["error"]
        return box["value"]  # type: ignore[no-any-return]


_default_gate: HttpGate | None = None
_default_key: tuple[str, str, str] | None = None
_lock = threading.Lock()


def default_gate() -> HttpGate | None:
    """The gate for this process, built from the environment on first use. None when
    GUARDIAN_URL is not set: then every tool is blocked (no gate, no call)."""
    global _default_gate, _default_key
    url = _env("GUARDIAN_URL", "SUPERVISOR_GATE_URL")
    if not url:
        return None
    key = (url, _env("GUARDIAN_AUTH"), _env("GUARDIAN_AGENT_KEY_FILE", "GUARDIAN_AGENT_KEY"))
    with _lock:
        if _default_gate is None or _default_key != key:
            try:
                credential: Any = credential_from_env(AGENT_ID)
            except CredentialError as exc:
                credential = BrokenCredential(str(exc))  # every check then answers GATE-AUTH
            timeout = float(_env("GUARDIAN_TIMEOUT_S") or 2.0)
            _default_gate = HttpGate(url, credential, timeout)
            _default_key = key
        return _default_gate


# ----------------------------------------------------------------------------- the decorator

_session_id: contextvars.ContextVar[str | None] = contextvars.ContextVar(
    "guardian_session_id", default=None
)
_consumer_id: contextvars.ContextVar[str | None] = contextvars.ContextVar(
    "guardian_consumer_id", default=None
)


def set_session(session_id: str | None, consumer_id: str | None = None) -> None:
    """Name the session (and the customer) of the calls that follow, for session limits."""
    _session_id.set(session_id)
    _consumer_id.set(consumer_id)


def _enforce(decision: Mapping[str, Any]) -> None:
    if decision.get("allow") is True:
        return
    reason = str(decision.get("reason", ""))
    if decision.get("action") == "pause" or "paused" in reason.lower():
        raise SupervisorPaused(decision)
    raise SupervisorBlocked(decision)


def _inline_redaction_on() -> bool:
    return os.environ.get("INLINE_REDACTION_ENABLED", "").strip().lower() in (
        "1",
        "true",
        "yes",
        "on",
    )


def _apply_transformed(
    sig: inspect.Signature,
    args: tuple[Any, ...],
    kwargs: dict[str, Any],
    decision: Mapping[str, Any],
) -> tuple[tuple[Any, ...], dict[str, Any]]:
    """Use the masked copy of the arguments that Guardian sent, when masking is switched on."""
    transformed = decision.get("transformed_args")
    if not _inline_redaction_on() or not isinstance(transformed, Mapping):
        return args, kwargs
    try:
        bound = sig.bind(*args, **kwargs)
        bound.apply_defaults()
        for name, value in transformed.items():
            if name in bound.arguments:
                bound.arguments[name] = value
        return bound.args, bound.kwargs
    except TypeError:
        raise SupervisorBlocked(_closed("GATE-REDACTION", "masking could not be applied")) from None


def supervised_tool(
    *names: str,
    gate: Any = None,
    tool_name: str | None = None,
    risk_class: str | None = None,
    agent_id: str | None = None,
    agent_version: str | None = None,
) -> Callable[[Any], Any]:
    """Ask Guardian before the tool runs. Forms:

        @supervised_tool("transfer")                  risk class comes from TOOLS
        @supervised_tool("transfer", "money")         risk class given here
        @supervised_tool(AGENT_ID, "1.0.0", "transfer", "money", gate=...)   as in the full SDK

    Works on ``def`` and ``async def``. ``gate`` is for tests; by default the gate is built from
    the environment."""
    if len(names) >= 3:
        agent_id, agent_version = agent_id or names[0], agent_version or names[1]
        tool_name = tool_name or names[2]
        risk_class = risk_class or (names[3] if len(names) > 3 else None)
    elif names:
        tool_name = tool_name or names[0]
        risk_class = risk_class or (names[1] if len(names) > 1 else None)
    if not tool_name:
        raise ValueError("supervised_tool needs the tool name")
    risk = risk_class or TOOLS.get(tool_name)
    if risk not in RISK_CLASSES:
        raise ValueError(f"tool {tool_name}: give a risk class {RISK_CLASSES} or add it to TOOLS")
    who, version = agent_id or AGENT_ID, agent_version or AGENT_VERSION

    def context() -> dict[str, Any]:
        out: dict[str, Any] = {"declared_risk_class": risk}
        if _session_id.get():
            out["session_id"] = _session_id.get()
        if _consumer_id.get():
            out["consumer_id"] = _consumer_id.get()
        return out

    def resolve() -> Any:
        found = gate or default_gate()
        if found is None:
            raise SupervisorBlocked(_closed("GATE-MISSING", "no guardian address: fail closed"))
        return found

    def decorate(fn: Any) -> Any:
        sig = inspect.signature(fn)

        def arguments(args: tuple[Any, ...], kwargs: dict[str, Any]) -> dict[str, Any]:
            try:
                bound = sig.bind(*args, **kwargs)
                bound.apply_defaults()
                return dict(bound.arguments)
            except TypeError:
                return dict(kwargs)

        if inspect.iscoroutinefunction(fn):

            @functools.wraps(fn)
            async def awrapper(*args: Any, **kwargs: Any) -> Any:
                found = resolve()
                decision = await asyncio.to_thread(
                    found.check, who, version, tool_name, arguments(args, kwargs), context()
                )
                _enforce(decision)
                args, kwargs = _apply_transformed(sig, args, kwargs, decision)
                return await fn(*args, **kwargs)

            return awrapper

        @functools.wraps(fn)
        def wrapper(*args: Any, **kwargs: Any) -> Any:
            found = resolve()
            decision = found.check(who, version, tool_name, arguments(args, kwargs), context())
            _enforce(decision)
            args, kwargs = _apply_transformed(sig, args, kwargs, decision)
            return fn(*args, **kwargs)

        return wrapper

    return decorate


def main() -> int:
    """``python guardian_client.py``: show the settings this process sees. Nothing is sent."""
    url = _env("GUARDIAN_URL", "SUPERVISOR_GATE_URL")
    try:
        credential = credential_from_env(AGENT_ID)
        kind = type(credential).__name__ if credential else "none (unsigned)"
    except CredentialError as exc:
        kind = f"problem: {exc}"
    lines = [
        f"[INFO] agent: {AGENT_ID} {AGENT_VERSION}, tools: {len(TOOLS)}",
        f"[{'OK' if url else 'FAIL'}] guardian address: {'set' if url else 'not set'}",
        f"[INFO] credential: {kind}",
    ]
    sys.stdout.write("\n".join(lines) + "\n")
    return 0 if url else 1


if __name__ == "__main__":
    raise SystemExit(main())
