"""guardian_client.py - connect your AI app to Guardian.

Put this one file next to your tool code. Put ONE line above each tool:

    from guardian_client import supervised_tool

    @supervised_tool("transfer")
    def transfer(...): ...

Before the tool runs, the line asks Guardian: may this call go on? If Guardian says no, the tool
does not run and the call raises SupervisorBlocked (SupervisorPaused when the agent is paused).
No Guardian, no call: if Guardian cannot be reached the tool is blocked. Only a read-only tool
may go on when Guardian cannot be reached.

Settings, as environment variables (nothing secret is written in this file):

    GUARDIAN_URL              the Guardian address, for example https://guardian.example.vn
    GUARDIAN_AGENT_KEY_FILE   path of the key file Guardian issued for this agent (HMAC), or
    GUARDIAN_AGENT_KEY        the key itself
    GUARDIAN_AUTH             hmac, databricks or auto (default)
    GUARDIAN_TIMEOUT_S        seconds to wait for Guardian (default 2)

On Databricks, with databricks-sdk installed, the app signs in as its own service principal. The
token is asked from the SDK for each call. It is never stored, printed or logged.

Standard library only. Python 3.11 or newer. This file was generated by Guardian: do not edit the
block between the two "baked" markers.
"""

