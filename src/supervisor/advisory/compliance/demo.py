"""Demo products for the compliance advisor (WP14): the three demo agents and corpus repos.

Deterministic (MockChat) and cached. Demo products use ``policies/baseline.yaml`` as their
policy (rules scoped to the agent), are supervised (basis ``deployed``) and take the catalogue
choices from the onboarding plan. Only ``demo_answers/<agent>.yaml`` adds answers; those are
synthetic and each one cites its source.

Not legal advice. Bank counsel must confirm.
"""

from __future__ import annotations

import re
from functools import cache
from pathlib import Path

from supervisor.adapters.llm.mock import MockChat
from supervisor.adapters.repo import LocalGitRepoReader
from supervisor.advisory.compliance.facts import apply_answers, from_onboard
from supervisor.advisory.compliance.model import ProductProfile
from supervisor.advisory.compliance.questionnaire import load_answers_file
from supervisor.catalogue import load_catalogue
from supervisor.onboard.discover import discover
from supervisor.onboard.instrument import render_policy
from supervisor.onboard.plan import plan
from supervisor.onboard.understand import understand
from supervisor.regkb.loader import REPO_ROOT

__all__ = ["DEMO_AGENTS", "corpus_product", "demo_product"]

DEMO_AGENTS = ("payments", "credit_prequal", "customer_service")
AGENTS_DIR = REPO_ROOT / "src" / "supervisor_agents"
CORPUS_DIR = REPO_ROOT / "data" / "corpus" / "repos"
ANSWERS_DIR = Path(__file__).resolve().parent / "demo_answers"
POLICY = REPO_ROOT / "policies" / "baseline.yaml"
POLICY_LABEL = "policies/baseline.yaml"
_NAME_RE = re.compile(r"^[a-z0-9_]+$")


def _build(folder: Path, prefix: str, *, deployed: bool) -> ProductProfile:
    disc = discover(LocalGitRepoReader(folder))
    chat = MockChat(model_id="mock-onboarding-v1")
    profile = understand(disc, chat)
    mp, _ = plan(disc.inventory, profile, load_catalogue())
    if deployed:
        texts: tuple[tuple[str, str], ...] = ((POLICY_LABEL, POLICY.read_text(encoding="utf-8")),)
    else:  # the policy the Onboarding Agent would propose in its pull request
        generated = render_policy(disc.inventory, profile, mp)
        texts = ((f"{prefix}policy.yaml (generated by onboarding)", generated),)
    return from_onboard(
        disc.inventory,
        profile,
        plan=mp,
        policy_texts=texts,
        basis="deployed" if deployed else "planned",
        file_prefix=prefix,
    )


@cache
def demo_product(agent_id: str) -> ProductProfile:
    """payments, credit_prequal or customer_service, as deployed with policies/baseline.yaml."""
    if agent_id not in DEMO_AGENTS:
        raise ValueError(f"unknown demo agent {agent_id!r}; use one of {', '.join(DEMO_AGENTS)}")
    product = _build(AGENTS_DIR / agent_id, f"src/supervisor_agents/{agent_id}/", deployed=True)
    answers = ANSWERS_DIR / f"{agent_id}.yaml"
    if answers.is_file():
        product = apply_answers(product, load_answers_file(answers))
    return product


@cache
def corpus_product(name: str) -> ProductProfile:
    """A repo of data/corpus/repos, onboarded as a planned product (no policy, no answers)."""
    if not _NAME_RE.match(name) or not (CORPUS_DIR / name).is_dir():
        raise ValueError(f"unknown corpus repo {name!r}")
    return _build(CORPUS_DIR / name, f"data/corpus/repos/{name}/", deployed=False)
