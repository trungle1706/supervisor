router = APIRouter(prefix="/gate", tags=["gate"])
log = logging.getLogger("supervisor.gateway")


def gateway_dep() -> Gateway:
    return wiring.get_gateway()


_GW: Gateway = Depends(gateway_dep)


_ID = r"^[A-Za-z0-9_.:@-]{1,128}$"


class CheckRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    agent_id: str = Field(pattern=_ID)
    agent_version: str = Field(pattern=_ID)
    tool_name: str = Field(pattern=_ID)
    args: dict[str, Any]
    context: dict[str, Any] | None = None
    # WP37 (DETECTORS_ENABLED): "output" checks what a tool returned (context.output) instead of
    # what the agent sends (args + context.tool_results). Rules are not evaluated on an output.
    direction: Literal["input", "output"] = "input"


class ControlRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    agent_id: str = Field(pattern=_ID)
    # Accepted for backward compatibility and IGNORED: the actor is the authenticated
    # principal (X-Dev-User on the laptop, SSO headers on the App), never a body field.
    principal: str | None = Field(default=None, max_length=256)
    reason: str = Field(default="", max_length=2000)


def _bad(message: str, **extra: Any) -> JSONResponse:
    return JSONResponse(status_code=400, content={"error": message, **extra})


async def _body(request: Request) -> Any:
    try:
        return await request.json()
    except BodyTooLarge:  # the body-limit middleware answers 413
        raise
    except Exception:  # noqa: BLE001 - any malformed body is a user error
        return None


def _validation_response(exc: ValidationError, audit_warning: str | None = None) -> JSONResponse:
    errors = [{"loc": list(e["loc"]), "msg": e["msg"]} for e in exc.errors()]
    extra = {"audit_warning": audit_warning} if audit_warning else {}
    return _bad("invalid request", detail=errors, **extra)


@router.post("/check", dependencies=[Depends(ingress_gate)])  # WP20: no-op unless enabled
async def check(request: Request, gw: Gateway = _GW) -> JSONResponse:
    try:
        req = CheckRequest.model_validate(await _body(request))
    except ValidationError as exc:
        return _validation_response(exc)
    extra: dict[str, Any] = {}
    headers: dict[str, str] = {}
    if getattr(gw, "detectors_on", False):
        # WP37: verdict contract v2. The correlation id comes from the caller (header) or is
        # generated by the gate; both are written to the decision, the span event and the chain.
        cid = request.headers.get(CORRELATION_HEADER)
        if cid is not None and not re.fullmatch(ID_PATTERN, cid):
            return _bad(f"{CORRELATION_HEADER} must match {ID_PATTERN}")
        extra = {"direction": req.direction, "request_id": request_id_of(request)}
        if cid:
            extra["correlation_id"] = cid
    elif req.direction != "input":
        return _bad("direction=output needs DETECTORS_ENABLED=1")
    # WP-D1: context.documents. Off (the default): refused, nothing else changes.
    if req.context is not None and "documents" in req.context:
        problem = documents_problem(req.context["documents"], getattr(gw, "documents_on", False))
        if problem:
            return _bad(problem)
        if req.direction != "input":
            return _bad("context.documents belongs to an input check")
    try:
        result = await run_in_threadpool(
            gw.check,
            req.agent_id,
            req.agent_version,
            req.tool_name,
            req.args,
            req.context,
            **extra,
        )
    except SupervisorError as exc:
        return _bad(str(exc))
    if result.get("correlation_id"):
        headers[CORRELATION_HEADER] = str(result["correlation_id"])
    return JSONResponse(content=result, headers=headers)


@router.get("/detectors", dependencies=[Depends(needs("gate.read", api=True))])
def detectors_catalogue(gw: Gateway = _GW) -> JSONResponse:
    """The detector catalogue served from code (WP37): slug, sides, protocols, presets and the
    settings schema. ``enabled`` says whether DETECTORS_ENABLED is on for this gateway."""
    gate = getattr(gw, "detector_gate", None)
    if gate is None:
        return JSONResponse(content={"enabled": False, "detectors": []})
    return JSONResponse(content={"enabled": True, "detectors": gate.registry.catalogue()})


def _audit_row(
    request: Request,
    gw: Gateway,
    action: str,
    *,
    attempt: bool,
    principal: str | None,
    agent_id: str | None,
    outcome: str,
    before: str | None,
    detail: str | None,
    permission: str | None = None,  # WP-P2
) -> str | None:
    """One ``console_action`` row for a control call (also with API_RBAC_ENABLED off; skipped
    only with CONSOLE_AUDIT_ENABLED=0 in dev mode). ``attempt`` = the row written BEFORE the
    side effect: a store error raises ``AuditUnavailable``. Otherwise returns a warning text
    when the outcome write failed."""
    if not audit_active(runtime_settings()):
        return None
    me = getattr(request.state, "principal", None)
    me = me if isinstance(me, AuthPrincipal) else None
    kw: dict[str, Any] = {
        "request_id": request_id_of(request),
        "actor": me,
        "actor_fallback": ("unverified:unknown", "unverified", get_provider().name),
        "permission": permission or f"agent.{action}",
        "method": request.method,
        "path": request.url.path,
        "target_kind": "agent" if agent_id else None,
        "target_id": agent_id,
        "before_hash": before,
    }
    if attempt:
        write_attempt(gw.tables, gw.clock, **kw)
        return None
    try:
        kw["after_hash"] = snapshot_hash(gw.states.state, "agent", agent_id) if agent_id else None
    except Exception as exc:  # noqa: BLE001 - a hash problem must not hide the outcome
        log.error("console_action hash failed: %s", type(exc).__name__)
        kw["after_hash"] = None
    warn = write_outcome(gw.tables, gw.clock, outcome=outcome, detail=detail, **kw)
    return warn


async def _control(request: Request, gw: Gateway, action: str) -> JSONResponse:
    try:
        req = ControlRequest.model_validate(await _body(request))
    except ValidationError as exc:
        warn = await run_in_threadpool(
            _audit_row,
            request,
            gw,
            action,
            attempt=False,
            principal=None,
            agent_id=None,
            outcome="error",
            before=None,
            detail="invalid_request",
        )
        return _validation_response(exc, warn)
    me = getattr(request.state, "principal", None)  # set by needs(..., control=True)
    principal = me.user_id if isinstance(me, AuthPrincipal) else None
    before = await run_in_threadpool(snapshot_hash, gw.states.state, "agent", req.agent_id)

    async def audit(outcome: str, detail: str | None) -> str | None:
        return await run_in_threadpool(
            _audit_row,
            request,
            gw,
            action,
            attempt=False,
            principal=principal,
            agent_id=req.agent_id,
            outcome=outcome,
            before=before,
            detail=detail,
        )

    if principal is None:
        warn = await audit("error", "principal_missing")
        return JSONResponse(
            status_code=403,
            content={"error": "identity required", **({"audit_warning": warn} if warn else {})},
        )
    try:  # M4: row 1 BEFORE the side effect; no row, no action
        await run_in_threadpool(
            _audit_row,
            request,
            gw,
            action,
            attempt=True,
            principal=principal,
            agent_id=req.agent_id,
            outcome="attempted",
            before=before,
            detail=None,
        )
    except AuditUnavailable as exc:
        return _bad(str(exc))
    states = gw.states
    fn = {
        "pause": states.pause,
        "resume": states.resume,
        "quarantine": states.quarantine,
        "release": states.release_quarantine,
    }[action]
    try:
        assert isinstance(me, AuthPrincipal)
        result = await run_in_threadpool(
            fn,
            req.agent_id,
            principal,
            req.reason,
            auth_method=me.auth_method,
            actor_kind=me.kind,
        )
    except SupervisorError as exc:
        warn = await audit("error", type(exc).__name__)
        return _bad(str(exc), **({"audit_warning": warn} if warn else {}))
    except Exception as exc:  # noqa: BLE001 - store outage etc.: 400 with a message, never 500
        warn = await audit("error", type(exc).__name__)
        return _bad(
            f"{action} failed: {type(exc).__name__}; see the server log",
            **({"audit_warning": warn} if warn else {}),
        )
    warn = await audit("ok", None)
    return JSONResponse(content={**result, "audit_warning": warn} if warn else result)


